'use strict';
const { _electron: electron, expect } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

(async () => {
  const desktop = path.resolve(__dirname, '..');
  const output = path.resolve(desktop, '../output/desktop');
  const fixture = fs.mkdtempSync(path.join(os.tmpdir(), 'optimus-desktop-smoke-'));
  fs.mkdirSync(output, {recursive: true});
  fs.rmSync(path.join(output,'smoke-result.json'),{force:true});
  fs.mkdirSync(path.join(fixture, 'project with spaces'));
  fs.writeFileSync(path.join(fixture, 'requirements.md'), '# An example project\nA small notes app.');
  const app = await electron.launch({args: [desktop], env: {...process.env, OPTIMUS_USER_DATA: path.join(fixture, 'user-data'), ELECTRON_RUN_AS_NODE: ''}});
  const errors = [];
  try {
    const page = await app.firstWindow();
    page.on('pageerror', error => errors.push(error.message));
    await page.getByRole('heading', {name: 'What are we building?'}).waitFor();
    await page.waitForFunction(() => window.optimus && !document.body.textContent.includes('Checking runtime'));
    const bootstrap = await page.evaluate(() => window.optimus.bootstrap());
    assert.equal(bootstrap.settings.maxTasks, 40);
    assert.ok(bootstrap.environment.checks.length > 0);
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
    await page.screenshot({path: path.join(output, 'desktop-new-build.png'), fullPage: true});
    await app.evaluate(({dialog}, directory) => {dialog.showOpenDialog = async (_window, options) => ({canceled:false,filePaths:[options.properties.includes('openDirectory') ? directory + '/project with spaces' : directory + '/requirements.md']});}, fixture);
    await page.getByRole('button', {name: 'Browse', exact: false}).first().click();
    await page.getByRole('textbox', {name: 'Project folder', exact: true}).waitFor();
    await expect(page.getByRole('textbox', {name: 'Project folder', exact: true})).toHaveValue(/project with spaces$/);
    await page.getByRole('button', {name: 'browse files', exact: true}).click();
    await page.getByText('requirements.md', {exact:true}).waitFor();
    await page.getByRole('spinbutton', {name:'Maximum number of tasks'}).fill('12');
    await page.getByText('Up to 12 tasks', {exact:true}).waitFor();
    await page.getByRole('spinbutton', {name:'Number of parallel workers'}).fill('5');
    await page.getByText('5 workers', {exact:true}).waitFor();
    await page.getByRole('button', {name:'Start build', exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Allow the agents'}).waitFor();
    assert.equal(fs.readdirSync(path.join(fixture,'project with spaces')).length,0);
    await page.getByRole('button',{name:'Dismiss error'}).click();
    await page.getByRole('button', {name:'AI providers', exact:true}).click();
    await page.getByRole('heading',{name:'Your AI, connected.'}).waitFor();
    await page.getByLabel('Claude Code authentication').selectOption('api');
    await page.getByLabel('Claude Code API key').waitFor();
    await page.getByRole('button',{name:'Save provider settings'}).click();
    await page.getByRole('status').filter({hasText:'Settings saved'}).waitFor();
    await page.screenshot({path:path.join(output,'desktop-providers.png'),fullPage:true});
    await page.getByRole('button',{name:'Preferences',exact:true}).click();
    await page.getByRole('heading',{name:'Local runtime',exact:true}).waitFor();
    await page.screenshot({path:path.join(output,'desktop-runtime.png'),fullPage:true});
    await page.getByRole('button',{name:'Projects',exact:true}).click();
    await page.getByRole('heading',{name:'Your first project starts here'}).waitFor();
    await page.getByRole('button',{name:'Build activity',exact:true}).click();
    await page.getByRole('heading',{name:'Room for your next big idea'}).waitFor();
    await app.evaluate(({shell}) => {globalThis.optimusSmokeOpenedLinks = []; shell.openExternal = async url => {globalThis.optimusSmokeOpenedLinks.push(url);};});
    await page.getByRole('button',{name:'About Optimus',exact:true}).click();
    await page.getByRole('heading',{name:'Build something worth sharing.'}).waitFor();
    await expect(page.getByText('Support is entirely voluntary. Optimus stays free.',{exact:true})).toBeVisible();
    await expect(page.locator('main')).not.toContainText(/buy once|renewal|checkout|license activation/i);
    await page.getByRole('button',{name:'View on GitHub',exact:false}).click();
    await page.getByRole('button',{name:'GitHub Sponsors',exact:false}).click();
    await expect.poll(() => app.evaluate(() => globalThis.optimusSmokeOpenedLinks)).toEqual(['https://github.com/slobodanmargetic988/Optimus-Prime-GSD-Fusion','https://github.com/sponsors/slobodanmargetic988']);
    const rejectedLinks = await page.evaluate(async () => {
      const urls = ['https://github.com/other/repository','https://github.com/login?return_to=https://example.com','https://github.com/slobodanmargetic988/Optimus-Prime-GSD-Fusion?redirect=https://example.com','https://github.com/sponsors/slobodanmargetic988#redirect','https://github.com/slobodanmargetic988/Optimus-Prime-GSD-Fusion/issues','https://github.com.evil.example/slobodanmargetic988/Optimus-Prime-GSD-Fusion','https://user@github.com/sponsors/slobodanmargetic988','http://github.com/sponsors/slobodanmargetic988','javascript:alert(1)'];
      return Promise.all(urls.map(async url => {try {await window.optimus.openExternal(url); return false;} catch {return true;}}));
    });
    assert.ok(rejectedLinks.every(Boolean),'Unapproved community links must be blocked by the main process');
    await page.evaluate(() => window.optimus.openExternal('https://www.python.org/downloads/'));
    await expect.poll(() => app.evaluate(() => globalThis.optimusSmokeOpenedLinks.length)).toBe(3);
    await expect(page.getByRole('status')).toHaveCount(0,{timeout:6000});
    await page.screenshot({path:path.join(output,'desktop-about.png'),fullPage:true});
    const planRun = {id:'fixture-plan',projectPath:path.join(fixture,'project with spaces'),name:'Verified plan fixture',provider:'codex',status:'completed',phase:'Completed',startedAt:new Date().toISOString(),summary:'Fixture plan completed; no model call.',planId:'fixture-plan-id',resumeAvailable:false,cycle:0,tasks:{total:12,done:0,active:0,blocked:0},workers:[],logs:[],config:{command:'plan',mode:'new',projectPath:path.join(fixture,'project with spaces'),mission:'Fixture only',scope:'',files:[],provider:'codex',workers:3,maxTasks:40,maxCycles:1,trustProject:true}};
    await app.evaluate(({BrowserWindow},run)=>BrowserWindow.getAllWindows()[0].webContents.send('optimus:run',run),planRun);
    await page.getByRole('button',{name:'Build activity',exact:true}).click();
    await page.getByRole('heading',{name:'Verified plan fixture'}).waitFor();
    await page.getByRole('button',{name:'Build this plan',exact:true}).click();
    await page.getByText('Build the saved plan.',{exact:true}).waitFor();
    assert.equal(await page.getByLabel('Allow agents to modify this project and run local commands.').isChecked(),false);
    await page.getByRole('button',{name:'Build this plan',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Allow the agents'}).waitFor();
    assert.equal(fs.readdirSync(path.join(fixture,'project with spaces')).length,0);
    await page.getByRole('button',{name:'Dismiss error'}).click();
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'smoke-result.json'),JSON.stringify({passed:true,checks: ['native isolated startup','preload API and context isolation','real runtime probe','native folder and attachment bridges','worker/task controls','permission gate prevents launch','provider settings persistence','all six navigation views','free About view and voluntary support','exact repository and sponsor links through IPC','unapproved community links rejected','existing setup documentation still allowed','real IPC run event rendering','guarded saved-plan action'],environment:bootstrap.environment,consoleErrors:errors,modelCalls:0},null,2));
    process.stdout.write('Desktop smoke passed: native startup, IPC, setup flows, settings, and navigation. No model calls.\n');
  } finally {await app.close();fs.rmSync(fixture,{recursive:true,force:true});}
})().catch(error=>{process.stderr.write(error.stack+'\n');process.exitCode=1;});
