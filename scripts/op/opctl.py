#!/usr/bin/env python3
"""CLI entrypoint for OP command surface."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

SCRIPT_DIR = Path(__file__).resolve().parent
SCRIPTS_ROOT = SCRIPT_DIR.parent
REPO_ROOT = SCRIPTS_ROOT.parent
for candidate in (REPO_ROOT, SCRIPTS_ROOT, SCRIPT_DIR):
    if str(candidate) not in sys.path:
        sys.path.insert(0, str(candidate))

from op_core import OpError, run_from_payload
from op_router import normalize_command

try:
    from scripts.install.common import resolve_context
    from scripts.install.config import resolve_effective_config
except Exception:  # pragma: no cover - runtime fallback when install modules unavailable
    resolve_context = None  # type: ignore[assignment]
    resolve_effective_config = None  # type: ignore[assignment]


def _parse_json_input(path: str) -> dict[str, Any]:
    raw = sys.stdin.read() if path == "-" else Path(path).read_text(encoding="utf-8")
    payload = json.loads(raw)
    if not isinstance(payload, dict):
        raise OpError("input_error", "input payload must be a JSON object", stage="input")
    return payload


def _print_json(payload: dict[str, Any], pretty: bool) -> None:
    if pretty:
        print(json.dumps(payload, indent=2, sort_keys=False))
    else:
        print(json.dumps(payload, separators=(",", ":"), sort_keys=False))


def _emit_start_banner(payload: dict[str, Any]) -> None:
    command_raw = str(payload.get("command") or "").strip()
    try:
        normalized = normalize_command(command_raw)
    except ValueError:
        return
    if not sys.stdout.isatty():
        return
    repo_root = str(payload.get("repo_root") or Path.cwd().resolve())
    canonical = str(getattr(normalized, "canonical", ""))
    if canonical == "op-build":
        print(f"[opctl] /op-build started for {repo_root}.", flush=True)
        print(
            f"[opctl] While waiting, run: opctl /op-report --repo-root {repo_root} --json-pretty",
            flush=True,
        )
        print(
            f"[opctl] Detailed state: opctl /op-status --repo-root {repo_root} --json-pretty",
            flush=True,
        )
        return
    if canonical == "op-simple-build":
        print(f"[opctl] /op-simple-build started for {repo_root}.", flush=True)
        print(
            f"[opctl] Runtime state lives in: {repo_root}/.op-simple/current",
            flush=True,
        )
        print(
            f"[opctl] While waiting, run: opctl /op-status --repo-root {repo_root} --json-pretty",
            flush=True,
        )
        return
    if canonical == "op-initialize":
        print(
            f"[opctl] /op-initialize started for {repo_root}. Initializing project and git baseline. This can take a few minutes.",
            flush=True,
        )
        print(
            f"[opctl] Planning will run automatically. You can check progress later with: opctl /op-report --repo-root {repo_root} --json-pretty",
            flush=True,
        )
        return
    if canonical == "op-plan":
        print(
            f"[opctl] /op-plan started for {repo_root}. Project plan is being generated by LLM with strict validation.",
            flush=True,
        )
        print(
            "[opctl] Have some patience, grab a coffee. Final JSON response will print when done.",
            flush=True,
        )
        return


def _resolve_configured_workflow(repo_root: str) -> dict[str, Any]:
    resolved: dict[str, Any] = {}
    if resolve_context is None or resolve_effective_config is None:
        return resolved
    mode_payloads = [
        {"mode": "local", "repo_root": repo_root},
        {"mode": "global"},
    ]
    for item in mode_payloads:
        try:
            ctx = resolve_context(item)
            resolved = resolve_effective_config({}, ctx)
        except Exception:
            continue
        errors = resolved.get("errors")
        if isinstance(errors, list) and errors:
            continue
        effective = resolved.get("effective_config")
        workflow = effective.get("workflow") if isinstance(effective, dict) else None
        if not isinstance(workflow, dict):
            continue
        value = workflow.get("sleep_minutes")
        try:
            sleep = float(value)
        except (TypeError, ValueError):
            sleep = None
        if isinstance(sleep, float) and sleep > 0:
            resolved["sleep_minutes"] = sleep
        configured_parallel = workflow.get("max_parallel_workers")
        try:
            parallel_workers = int(configured_parallel)
        except (TypeError, ValueError):
            parallel_workers = None
        if isinstance(parallel_workers, int) and parallel_workers > 0:
            resolved["max_parallel_workers"] = parallel_workers
        fan_in_value = workflow.get("enable_artifact_fan_in")
        if isinstance(fan_in_value, bool):
            resolved["enable_artifact_fan_in"] = fan_in_value
        boss_model = workflow.get("boss_model")
        if isinstance(boss_model, str) and boss_model.strip():
            resolved["boss_model"] = boss_model.strip()
        boss_reasoning_effort = workflow.get("boss_reasoning_effort")
        if isinstance(boss_reasoning_effort, str) and boss_reasoning_effort.strip():
            resolved["boss_reasoning_effort"] = boss_reasoning_effort.strip()
        if resolved:
            return resolved
    return resolved


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="OP command surface (map/new-project/plan/initialize/build/simple-build/health/status/report/resume)"
    )
    parser.add_argument("--input-json", help="JSON payload path or '-' for stdin")
    parser.add_argument("--command")
    parser.add_argument("--repo-root")
    parser.add_argument("--mission")
    parser.add_argument("--mission-file")
    parser.add_argument("--scope")
    parser.add_argument("--scope-file")
    parser.add_argument("--override-old-plan", action="store_true")
    parser.add_argument("--constraint", action="append")
    parser.add_argument("--non-interactive", action="store_true")
    parser.add_argument("--output-mode", choices=["json", "json+text"], default=None)
    parser.add_argument("--max-build-cycles", type=int)
    parser.add_argument("--max-parallel-workers", type=int)
    parser.add_argument("--sleep-minutes", type=float)
    parser.add_argument("--run-base-source-branch")
    parser.add_argument("--profile")
    parser.add_argument("--executor-provider", choices=["codex", "openrouter", "blackbox"], default=None)
    parser.add_argument("--executor-model")
    parser.add_argument("--blackbox-lane", choices=["free", "api_key"], default=None)
    parser.add_argument("--allow-worker-executor-override", action="store_true")
    parser.add_argument("--cycle-release-mode", choices=["token_conservative", "max_work"], default=None)
    parser.add_argument("--cycle-release-timeout-seconds", type=int)
    parser.add_argument("--cycle-release-poll-seconds", type=int)
    parser.add_argument("--boss-model")
    parser.add_argument("--boss-reasoning-effort")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--reset-exhausted-retries", action="store_true")
    parser.add_argument("--json-pretty", action="store_true")
    return parser.parse_args()


def merge_payload(args: argparse.Namespace) -> dict[str, Any]:
    payload: dict[str, Any] = {}
    if args.input_json:
        payload = _parse_json_input(args.input_json)

    if args.command is not None:
        payload["command"] = args.command
    if args.repo_root is not None:
        payload["repo_root"] = args.repo_root
    if args.mission is not None:
        payload["mission"] = args.mission
    if args.mission_file is not None:
        payload["mission_file"] = args.mission_file
    if args.scope is not None:
        payload["scope"] = args.scope
    if args.scope_file is not None:
        payload["scope_file"] = args.scope_file
    if args.override_old_plan:
        payload["override_old_plan"] = True
    if args.constraint is not None:
        payload["constraints"] = args.constraint
    if args.non_interactive:
        payload["non_interactive"] = True
    if args.output_mode is not None:
        payload["output_mode"] = args.output_mode
    if args.max_build_cycles is not None:
        payload["max_build_cycles"] = args.max_build_cycles
    if args.max_parallel_workers is not None:
        payload["max_parallel_workers"] = args.max_parallel_workers
    if args.sleep_minutes is not None:
        payload["sleep_minutes"] = args.sleep_minutes
    if args.run_base_source_branch is not None:
        payload["run_base_source_branch"] = args.run_base_source_branch
    if args.profile is not None:
        payload["profile"] = args.profile
        payload["codex_profile"] = args.profile
    if args.executor_provider is not None:
        payload["executor_provider"] = args.executor_provider
    if args.executor_model is not None:
        payload["executor_model"] = args.executor_model
    if args.blackbox_lane is not None:
        payload["blackbox_lane"] = args.blackbox_lane
    if args.allow_worker_executor_override:
        payload["allow_worker_executor_override"] = True
    if args.cycle_release_mode is not None:
        payload["cycle_release_mode"] = args.cycle_release_mode
    if args.cycle_release_timeout_seconds is not None:
        payload["cycle_release_timeout_seconds"] = args.cycle_release_timeout_seconds
    if args.cycle_release_poll_seconds is not None:
        payload["cycle_release_poll_seconds"] = args.cycle_release_poll_seconds
    if args.boss_model is not None:
        payload["boss_model"] = args.boss_model
    if args.boss_reasoning_effort is not None:
        payload["boss_reasoning_effort"] = args.boss_reasoning_effort
    if args.dry_run:
        payload["dry_run"] = True
    if args.reset_exhausted_retries:
        payload["reset_exhausted_retries"] = True

    payload.setdefault("repo_root", str(Path.cwd().resolve()))
    payload.setdefault("non_interactive", True)
    payload.setdefault("output_mode", "json")
    payload.setdefault("executor_provider", "codex")
    payload.setdefault("blackbox_lane", "free")
    payload.setdefault("allow_worker_executor_override", False)
    payload.setdefault("cycle_release_mode", "token_conservative")
    payload.setdefault("cycle_release_timeout_seconds", 300)
    payload.setdefault("cycle_release_poll_seconds", 5)

    command_raw = str(payload.get("command") or "").strip()
    try:
        canonical = normalize_command(command_raw).canonical
    except ValueError:
        canonical = ""

    if canonical in {"op-build", "op-resume", "op-simple-build"}:
        workflow = _resolve_configured_workflow(str(payload["repo_root"]))
        if "sleep_minutes" not in payload:
            configured_sleep = workflow.get("sleep_minutes")
            if isinstance(configured_sleep, (int, float)):
                payload["sleep_minutes"] = float(configured_sleep)
        if "max_parallel_workers" not in payload:
            configured_parallel = workflow.get("max_parallel_workers")
            if isinstance(configured_parallel, int) and configured_parallel > 0:
                payload["max_parallel_workers"] = configured_parallel
        if "enable_artifact_fan_in" not in payload:
            configured_fan_in = workflow.get("enable_artifact_fan_in")
            if isinstance(configured_fan_in, bool):
                payload["enable_artifact_fan_in"] = configured_fan_in
        if canonical == "op-simple-build" and "boss_model" not in payload:
            configured_model = workflow.get("boss_model")
            if isinstance(configured_model, str) and configured_model.strip():
                payload["boss_model"] = configured_model.strip()
        if canonical == "op-simple-build" and "boss_reasoning_effort" not in payload:
            configured_effort = workflow.get("boss_reasoning_effort")
            if isinstance(configured_effort, str) and configured_effort.strip():
                payload["boss_reasoning_effort"] = configured_effort.strip()

    if "sleep_minutes" not in payload:
        command_raw = str(payload.get("command") or "").strip()
        try:
            canonical = normalize_command(command_raw).canonical
        except ValueError:
            canonical = ""
        if canonical in {"op-build", "op-resume"}:
            payload["sleep_minutes"] = 2.0
        elif canonical == "op-simple-build":
            payload["sleep_minutes"] = 5.0

    if "enable_artifact_fan_in" not in payload:
        command_raw = str(payload.get("command") or "").strip()
        try:
            canonical = normalize_command(command_raw).canonical
        except ValueError:
            canonical = ""
        if canonical in {"op-build", "op-resume", "op-simple-build"}:
            payload["enable_artifact_fan_in"] = False
    if "max_parallel_workers" not in payload:
        command_raw = str(payload.get("command") or "").strip()
        try:
            canonical = normalize_command(command_raw).canonical
        except ValueError:
            canonical = ""
        if canonical == "op-simple-build":
            payload["max_parallel_workers"] = 8
    return payload


def main() -> int:
    args = parse_args()
    try:
        payload = merge_payload(args)
        _emit_start_banner(payload)
        result = run_from_payload(payload)
        _print_json(result, args.json_pretty)
        return 0 if result.get("ok") else 1
    except OpError as exc:
        out = {
            "schema_version": "1.0",
            "tool": "opctl",
            "tool_version": "0.1.0",
            "ok": False,
            "command": payload.get("command") if "payload" in locals() else args.command,
            "status": "failed",
            "summary": "Command failed.",
            "errors": [{"code": exc.code, "message": exc.message, "stage": exc.stage}],
            "warnings": [],
            "artifacts": [],
            "next_action": None,
            "state_ref": None,
        }
        _print_json(out, args.json_pretty)
        return 1
    except json.JSONDecodeError as exc:
        out = {
            "schema_version": "1.0",
            "tool": "opctl",
            "tool_version": "0.1.0",
            "ok": False,
            "status": "failed",
            "summary": "Invalid JSON input.",
            "errors": [{"code": "input_error", "message": f"invalid JSON: {exc}", "stage": "input"}],
            "warnings": [],
            "artifacts": [],
            "next_action": None,
            "state_ref": None,
        }
        _print_json(out, args.json_pretty)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
